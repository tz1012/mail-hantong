//! Unix P-256 signing over an opaque PKCS#8 key.
//!
//! The key is accepted only from the OS-backed secret store and is retained
//! inside this module.  Callers receive the fixed wire forms required by the
//! existing IPC contract, never private-key bytes.

use crate::unix_secret_store::{ProtectedBytes, UnixSecretError};
use hantong_contracts::platform::{OpaqueSigner as OpaqueSignerContract, PlatformError};
#[cfg(any(target_os = "linux", target_os = "macos"))]
use std::path::Path;

#[cfg(any(target_os = "linux", target_os = "macos"))]
use ring::signature::KeyPair;

pub const PUBLIC_KEY_LEN: usize = 72;
pub const SIGNATURE_LEN: usize = 64;
const MAX_MESSAGE: usize = 32_768;

pub struct OpaqueSigner {
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    key: ring::signature::EcdsaKeyPair,
}

impl std::fmt::Debug for OpaqueSigner {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("OpaqueSigner(<redacted>)")
    }
}

impl OpaqueSigner {
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    pub(crate) fn from_pkcs8(bytes: ProtectedBytes) -> Result<Self, UnixSecretError> {
        if bytes.as_bytes_in_secrets().len() > 4096 {
            return Err(UnixSecretError::SecretTooLarge);
        }
        let key = ring::signature::EcdsaKeyPair::from_pkcs8(
            &ring::signature::ECDSA_P256_SHA256_FIXED_SIGNING,
            bytes.as_bytes_in_secrets(),
            &ring::rand::SystemRandom::new(),
        )
        .map_err(|_| UnixSecretError::InvalidSecret)?;
        Ok(Self { key })
    }

    /// Create a signing key exactly once. Existing entries are never replaced
    /// and missing entries are never regenerated by the load path.
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    pub fn create(
        store: &crate::unix_secret_store::UnixSecretStore,
        guard: &crate::unix_secret_store::UnixSecretMutationGuard,
        selector: &crate::unix_secret_store::UnixSecretSelector,
        expected_public_key: Option<[u8; PUBLIC_KEY_LEN]>,
    ) -> Result<Self, UnixSecretError> {
        let pkcs8 = ring::signature::EcdsaKeyPair::generate_pkcs8(
            &ring::signature::ECDSA_P256_SHA256_FIXED_SIGNING,
            &ring::rand::SystemRandom::new(),
        )
        .map_err(|_| UnixSecretError::StoreFailure)?;
        let raw = crate::SensitiveBuffer(pkcs8.as_ref().to_vec());
        let protected = ProtectedBytes::from_backend(raw.as_slice().to_vec())?;
        let signer = Self::from_pkcs8(protected)?;
        let public = signer.public_key()?;
        if expected_public_key.is_some_and(|expected| expected != public) {
            return Err(UnixSecretError::InvalidSecret);
        }
        let kind = selector.kind();
        if !kind.is_signing_key() {
            return Err(UnixSecretError::InvalidSelector);
        }
        let result = store.create(guard, selector, raw.as_slice(), kind);
        result.map(|()| signer)
    }

    #[cfg(any(target_os = "linux", target_os = "macos"))]
    pub fn load(
        store: &crate::unix_secret_store::UnixSecretStore,
        selector: &crate::unix_secret_store::UnixSecretSelector,
        expected_public_key: [u8; PUBLIC_KEY_LEN],
    ) -> Result<Self, UnixSecretError> {
        let key = Self::from_pkcs8(store.read(selector)?)?;
        if key.public_key()? != expected_public_key {
            return Err(UnixSecretError::InvalidSecret);
        }
        Ok(key)
    }

    #[cfg(any(target_os = "linux", target_os = "macos"))]
    pub fn public_key(&self) -> Result<[u8; PUBLIC_KEY_LEN], UnixSecretError> {
        let point = self.key.public_key().as_ref();
        if point.len() != 65 || point[0] != 4 {
            return Err(UnixSecretError::InvalidSecret);
        }
        // Preserve the Windows CNG BCRYPT_ECDSA_PUBLIC_P256_BLOB wire shape:
        // magic "ECS1", cbKey=32, then X and Y coordinates.
        let mut output = [0_u8; PUBLIC_KEY_LEN];
        output[..4].copy_from_slice(b"ECS1");
        output[4..8].copy_from_slice(&32_u32.to_le_bytes());
        output[8..].copy_from_slice(&point[1..]);
        Ok(output)
    }

    #[cfg(any(target_os = "linux", target_os = "macos"))]
    pub fn sign(&self, message: &[u8]) -> Result<[u8; SIGNATURE_LEN], UnixSecretError> {
        if message.is_empty() || message.len() > MAX_MESSAGE {
            return Err(UnixSecretError::InvalidSecret);
        }
        let signature = self
            .key
            .sign(&ring::rand::SystemRandom::new(), message)
            .map_err(|_| UnixSecretError::StoreFailure)?;
        signature
            .as_ref()
            .try_into()
            .map_err(|_| UnixSecretError::InvalidSecret)
    }
}

/// Loads the server signing key from the OS credential store without exposing
/// its protected bytes. The selector is derived only from the staged key id.
#[cfg(any(target_os = "linux", target_os = "macos"))]
pub fn load_server_signing_key(
    root: impl AsRef<Path>,
    key_id: [u8; 32],
    expected_public_key: [u8; PUBLIC_KEY_LEN],
) -> Result<OpaqueSigner, UnixSecretError> {
    let _guard = hantong_platform::unix_paths::UnixDirectoryGuard::open(root.as_ref(), true)
        .map_err(|_| UnixSecretError::Unavailable)?;
    let store = crate::unix_secret_store::UnixSecretStore::new();
    let selector = server_selector(key_id)?;
    OpaqueSigner::load(&store, &selector, expected_public_key)
}

/// Loads a staged server key before its public key is published in Store.
/// This is only for recovery of a `Creating` identity row.
#[cfg(any(target_os = "linux", target_os = "macos"))]
pub fn load_staged_server_signing_key(
    root: impl AsRef<Path>,
    key_id: [u8; 32],
) -> Result<OpaqueSigner, UnixSecretError> {
    let _guard = hantong_platform::unix_paths::UnixDirectoryGuard::open(root.as_ref(), true)
        .map_err(|_| UnixSecretError::Unavailable)?;
    let store = crate::unix_secret_store::UnixSecretStore::new();
    let selector = server_selector(key_id)?;
    OpaqueSigner::from_pkcs8(store.read(&selector)?)
}

/// Creates a staged server signing key exactly once in the OS credential
/// store. Existing entries are reported to the coordinator and never replaced.
#[cfg(any(target_os = "linux", target_os = "macos"))]
pub fn create_server_signing_key(
    root: impl AsRef<Path>,
    key_id: [u8; 32],
) -> Result<OpaqueSigner, UnixSecretError> {
    let guard = hantong_platform::unix_paths::UnixDirectoryGuard::open(root.as_ref(), true)
        .map_err(|_| UnixSecretError::Unavailable)?;
    let store = crate::unix_secret_store::UnixSecretStore::new();
    let mutation = crate::unix_secret_store::UnixSecretMutationGuard::lock(&guard)?;
    let selector = server_selector(key_id)?;
    OpaqueSigner::create(&store, &mutation, &selector, None)
}

/// Loads or creates the client signing key for one registration. Private key
/// material remains inside the Unix credential store and the opaque signer.
#[cfg(any(target_os = "linux", target_os = "macos"))]
pub fn load_client_signing_key(
    root: impl AsRef<Path>,
    registration_id: [u8; 16],
    expected_public_key: Option<[u8; PUBLIC_KEY_LEN]>,
) -> Result<OpaqueSigner, UnixSecretError> {
    let guard = hantong_platform::unix_paths::UnixDirectoryGuard::open(root.as_ref(), true)
        .map_err(|_| UnixSecretError::Unavailable)?;
    let store = crate::unix_secret_store::UnixSecretStore::new();
    let key_id = hantong_platform::client_key_id_for_registration(registration_id)
        .map_err(|_| UnixSecretError::InvalidSelector)?;
    let selector = client_selector(key_id)?;
    match expected_public_key {
        Some(public) => OpaqueSigner::load(&store, &selector, public),
        None => {
            let mutation = crate::unix_secret_store::UnixSecretMutationGuard::lock(&guard)?;
            match OpaqueSigner::create(&store, &mutation, &selector, None) {
                Ok(key) => Ok(key),
                Err(UnixSecretError::AlreadyExists) => {
                    let existing = store.read(&selector)?;
                    OpaqueSigner::from_pkcs8(existing)
                }
                Err(error) => Err(error),
            }
        }
    }
}

#[cfg(any(target_os = "linux", target_os = "macos"))]
fn client_selector(
    key_id: [u8; 32],
) -> Result<crate::unix_secret_store::UnixSecretSelector, UnixSecretError> {
    let id = hantong_contracts::wire_hex::encode(&key_id);
    crate::unix_secret_store::UnixSecretSelector::new(
        crate::unix_secret_store::UnixSecretKind::ClientSigningKey,
        Some(&id),
        1,
    )
}

#[cfg(any(target_os = "linux", target_os = "macos"))]
fn server_selector(
    key_id: [u8; 32],
) -> Result<crate::unix_secret_store::UnixSecretSelector, UnixSecretError> {
    let id = hantong_contracts::wire_hex::encode(&key_id);
    crate::unix_secret_store::UnixSecretSelector::new(
        crate::unix_secret_store::UnixSecretKind::ServerSigningKey,
        Some(&id),
        1,
    )
}

impl OpaqueSignerContract for OpaqueSigner {
    fn public_key(&self) -> Result<[u8; 72], PlatformError> {
        OpaqueSigner::public_key(self).map_err(|error| match error {
            UnixSecretError::InvalidSecret => PlatformError::InvalidInput,
            _ => PlatformError::Unsupported,
        })
    }

    fn sign(&mut self, transcript: &[u8]) -> Result<[u8; 64], PlatformError> {
        OpaqueSigner::sign(self, transcript).map_err(|error| match error {
            UnixSecretError::InvalidSecret => PlatformError::InvalidInput,
            _ => PlatformError::Unsupported,
        })
    }
}

#[cfg(test)]
mod tests {
    #[cfg(any(target_os = "linux", target_os = "macos"))]
    use ring::signature::KeyPair;

    #[cfg(any(target_os = "linux", target_os = "macos"))]
    #[test]
    fn sec01_synthetic_pkcs8_signs_fixed_wire_and_rejects_wrong_pin() {
        let rng = ring::rand::SystemRandom::new();
        let pkcs8 = ring::signature::EcdsaKeyPair::generate_pkcs8(
            &ring::signature::ECDSA_P256_SHA256_FIXED_SIGNING,
            &rng,
        )
        .unwrap();
        let signer = super::OpaqueSigner::from_pkcs8(
            super::ProtectedBytes::from_backend(pkcs8.as_ref().to_vec()).unwrap(),
        )
        .unwrap();
        let public = signer.public_key().unwrap();
        assert_eq!(&public[..4], b"ECS1");
        assert_eq!(&public[4..8], &32_u32.to_le_bytes());
        let signature = signer.sign(b"unix-synthetic-transcript").unwrap();
        let point = signer.key.public_key().as_ref().to_vec();
        ring::signature::UnparsedPublicKey::new(
            &ring::signature::ECDSA_P256_SHA256_FIXED,
            point.as_slice(),
        )
        .verify(b"unix-synthetic-transcript", &signature)
        .unwrap();
        assert!(
            hantong_platform::verify_signature(&public, b"unix-synthetic-transcript", &signature,)
                .unwrap()
        );
        assert!(
            !hantong_platform::verify_signature(&public, b"changed-transcript", &signature,)
                .unwrap()
        );
        let mut malformed = public;
        malformed[8..].fill(0);
        assert!(hantong_platform::validate_public_key(&malformed).is_err());
        assert_eq!(
            signer.public_key().unwrap(),
            public,
            "public key pin must remain stable"
        );
        assert!(
            super::OpaqueSigner::from_pkcs8(
                super::ProtectedBytes::from_backend(vec![0x30; 32]).unwrap()
            )
            .is_err()
        );
        assert!(signer.sign(&vec![0_u8; 32_769]).is_err());
    }
}
